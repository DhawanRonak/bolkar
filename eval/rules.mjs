import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const B = createRequire(import.meta.url)('../speech.js');
for (const [input,expected] of [['९८७६५४३२१०','9876543210'],['+91 9876543210','9876543210'],['09876543210','9876543210']]) assert.equal(B.mobile(input).value,expected);
for (const input of ['9876543210 banana','9876543210 double','double 9876543210']) assert.equal(B.mobile(input).ok,false,input);
for (const input of ['-150000','minus 2 lakh','2 banana lakh','2 lakh fifty mystery','sadhe']) assert.equal(B.amount(input).ok,false,input);
assert.equal(B.amount('₹1,50,000').value,150000);
assert.equal(B.amount('12000 per month').value,144000);
assert.equal(B.amount('अस्सी हजार').value,80000);
assert.equal(B.pin('०१२३४५').ok,false);
assert.equal(B.date('31 February 2005').ok,false);
assert.equal(B.date('29 February 2004').value,'29-02-2004');
assert.equal(B.date('05-03-2005').value,'05-03-2005');
for (const input of ['!!!','123','A २','<script>','a'.repeat(101)]) assert.equal(B.name(input).ok,false,input);
assert.equal(B.name('मेरा नाम सुनीता देवी है').value,'सुनीता देवी');
assert.equal(B.choice('male female',{Male:['male'],Female:['female']}).ok,false);
assert.equal(B.yesNo('no, not correct'),'no');
assert.equal(B.readBack(B.FIELDS[3],'9876543210','en').shown,'98765 43210');
console.log('Additional rule regressions passed.');
